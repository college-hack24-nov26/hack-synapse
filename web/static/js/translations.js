let currentLang = "en";
try { const saved = localStorage.getItem("neuroglove_lang"); if (TRANSLATIONS[saved]) currentLang = saved; } catch (_) {}

function t(key) {
    if (!key) return "";
    const langDict = TRANSLATIONS[currentLang] || TRANSLATIONS.en;
    if (langDict && langDict[key] !== undefined) {
        return langDict[key];
    }
    // Fallback to English
    if (TRANSLATIONS.en && TRANSLATIONS.en[key] !== undefined) {
        return TRANSLATIONS.en[key];
    }
    return key;
}

function setLanguage(lang) {
    if (!TRANSLATIONS[lang]) return;
    currentLang = lang;
    try { localStorage.setItem("neuroglove_lang", lang); } catch (_) {}
    applyTranslations();

    // Update language select dropdown
    const langSelect = document.getElementById("langSelect");
    if (langSelect && langSelect.value !== lang) {
        langSelect.value = lang;
    }

    // Update active state on language pills if any exist
    document.querySelectorAll(".lang-btn").forEach(btn => {
        if (btn.dataset.lang === lang) {
            btn.classList.add("active");
        } else {
            btn.classList.remove("active");
        }
    });

    // Notify registered modules
    if (typeof window.onLanguageChanged === "function") {
        window.onLanguageChanged(lang);
    }
}

function applyTranslations() {
    // 1. All elements with [data-i18n]
    document.querySelectorAll("[data-i18n]").forEach(el => {
        const key = el.getAttribute("data-i18n");
        const translation = t(key);
        if (!translation) return;

        if (el.tagName === "INPUT" && (el.type === "button" || el.type === "submit")) {
            el.value = translation;
        } else if (el.hasAttribute("placeholder")) {
            el.setAttribute("placeholder", translation);
        } else if (el.hasAttribute("title") && !el.textContent.trim()) {
            el.setAttribute("title", translation);
        } else {
            el.textContent = translation;
        }
    });

    document.documentElement.lang = currentLang;
    window.ngI18n?.apply();

    // 2. Refresh dynamic components if initialized
    if (window.handGlossary && typeof window.handGlossary.updateLanguage === "function") {
        window.handGlossary.updateLanguage(currentLang);
    }
    if (window.rehabGames && typeof window.rehabGames.updateUI === "function") {
        window.rehabGames.updateUI();
    }
}

document.addEventListener("DOMContentLoaded", () => {
    applyTranslations();
    const langSelect = document.getElementById("langSelect");
    if (langSelect) langSelect.value = currentLang;
    const activeBtn = document.querySelector(`.lang-btn[data-lang="${currentLang}"]`);
    if (activeBtn) activeBtn.classList.add("active");
});
